import { chromium } from 'playwright';
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } }); const p = await ctx.newPage();
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
await p.goto('http://localhost:3100/episodes'); await p.waitForTimeout(1200);
const q = (fn) => p.evaluate(fn);
console.log('rows', await q(() => document.querySelectorAll('.pl-row').length), 'nav', await q(() => document.querySelector('.nav').className));
await p.click('.pl-head .filter-btn:nth-child(2)'); await p.waitForTimeout(300);
console.log('skim cols', await q(() => getComputedStyle(document.querySelector('.pl-list')).gridTemplateColumns));
await p.reload(); await p.waitForTimeout(1000);
console.log('skim persisted', await q(() => document.querySelector('.pl-list').classList.contains('is-skim')));
await p.click('.pl-head .filter-btn:nth-child(1)');
await p.hover('.pl-row'); await p.waitForTimeout(500);
console.log('hover links opacity', await q(() => getComputedStyle(document.querySelector('.pl-row .ep-card__links')).opacity));
await p.click('.pl-row button.pl-play'); await p.waitForTimeout(800);
console.log('player shown', await q(() => [!!document.querySelector('.player'), document.querySelector('.player__title')?.textContent, document.querySelector('.pl-row .pl-play')?.getAttribute('aria-pressed')]));
await p.goto('http://localhost:3100/episodes?q=disney'); await p.waitForTimeout(1000);
console.log('search', await q(() => [document.querySelector('.pl-head h1').textContent, [...document.querySelectorAll('.pl-title')].map(e => e.textContent)]));
await p.setViewportSize({ width: 768, height: 900 }); await p.goto('http://localhost:3100/episodes'); await p.waitForTimeout(800);
await p.click('.pl-bar .icon-btn'); await p.waitForTimeout(600);
console.log('tablet sidebar', await q(() => [document.querySelector('.pl-sidebar-pop').className, getComputedStyle(document.querySelector('.pl-sidebar')).opacity]));
await p.keyboard.press('Escape'); await p.waitForTimeout(500);
console.log('closed', await q(() => document.querySelector('.pl-sidebar-pop').className));
await p.click('.nav__menu-btn'); await p.waitForTimeout(400);
console.log('menu at 768', await q(() => document.querySelector('#menu-popup').className));
console.log('errors', errs); await b.close();
