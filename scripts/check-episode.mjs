import { chromium } from 'playwright';
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
await p.goto('http://localhost:3100/episodes/seinfeld'); await p.waitForTimeout(1500);
const q = (fn) => p.evaluate(fn);
console.log('nav theme', await q(() => document.querySelector('.nav').className));
await p.click('a[href="#transcript"]'); await p.waitForTimeout(500);
console.log('transcript open', await q(() => [location.hash, getComputedStyle(document.querySelector('.sheet .sheet__panel')).transform, document.querySelector('.player-wrap').className]));
await p.click('.sheet.is-open .toc-item:nth-child(5)'); await p.waitForTimeout(900);
console.log('active chapter', await q(() => document.querySelector('.sheet.is-open .toc-item.is-active')?.textContent));
await p.keyboard.press('Escape'); await p.waitForTimeout(500);
console.log('closed', await q(() => [location.hash, document.querySelectorAll('.sheet.is-open').length]));
await p.click('.ep-art'); await p.waitForTimeout(600);
console.log('zoom', await q(() => document.querySelector('.zoom img')?.style.transform));
await p.keyboard.press('Escape'); await p.waitForTimeout(500);
console.log('zoom closed', await q(() => !document.querySelector('.zoom')));
const h0 = await q(() => document.querySelector('.player').offsetHeight);
await p.click('.player__min'); await p.waitForTimeout(600);
const h1 = await q(() => document.querySelector('.player').offsetHeight);
await p.click('.player__head'); await p.waitForTimeout(600);
console.log('player heights expanded/min/re-expanded', h0, h1, await q(() => document.querySelector('.player').offsetHeight));
await p.click('.player__speed'); console.log('speed', await q(() => document.querySelector('.player__speed').textContent));
await p.evaluate(() => document.querySelector('.slider').scrollIntoView()); await p.waitForTimeout(300);
await p.click('.slider-arrow[aria-label=Next]'); await p.waitForTimeout(800);
console.log('slider scrollLeft', await q(() => [document.querySelector('.slider__track').scrollLeft, document.querySelector('.slider-arrow[aria-label=Previous]').disabled, document.querySelector('.nav').className]));
await p.goto('http://localhost:3100/episodes/seinfeld#sources'); await p.waitForTimeout(800);
console.log('deep link sources', await q(() => document.querySelectorAll('.sheet.is-open').length));
console.log('errors', errs);
await b.close();
